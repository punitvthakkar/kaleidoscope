// Generates core/params_gen.h from the parameter schema inside ../index.html, so the
// web page stays the single source of truth for parameters, palettes and defaults.
import fs from 'node:fs';
const [,, htmlPath, outPath] = process.argv;
const html = fs.readFileSync(htmlPath, 'utf8');
const blocks = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const src = blocks.find((b) => b.includes('const SCHEMA = {'));
if (!src) throw new Error('schema block not found in ' + htmlPath);
const S = new Function(src + '; return { SCHEMA, PALETTES, SYSTEM_DEFAULTS, MODES, GENERATORS, BRUSHES, INK_COLORS, PEN_PATHS, RM_SHAPES, RM_LOOKS };')();
const num = (v) => (Number.isInteger(v) ? v + '.0f' : v + 'f');
const id = (s) => String(s).replace(/[^A-Za-z0-9_]/g, '_');
let o = '// GENERATED by tools/gen_params.mjs from index.html. Do not edit.\n#pragma once\n#include <cstddef>\n#include <cstring>\n\n';
for (const [name, list] of Object.entries({ MODE: S.MODES, GEN: S.GENERATORS, BRUSH: S.BRUSHES, INKCOLOR: S.INK_COLORS, PENPATH: S.PEN_PATHS, RMSHAPE: S.RM_SHAPES, RMLOOK: S.RM_LOOKS })) {
  o += `enum { ${list.map((v, i) => `${name}_${id(v)} = ${i}`).join(', ')}, ${name}_COUNT = ${list.length} };\n`;
}
const palNames = Object.keys(S.PALETTES);
o += `\nenum { PALETTE_COUNT = ${palNames.length} };\n`;
o += `static const char* const PALETTE_NAMES[PALETTE_COUNT] = { ${palNames.map((n) => `"${n}"`).join(', ')} };\n`;
o += `// [palette][a,b,c,d][rgb]: colour = a + b*cos(2pi*(c*t+d))\nstatic const float PALETTES[PALETTE_COUNT][4][3] = {\n${palNames.map((n) => '  {' + S.PALETTES[n].map((r) => '{' + [...r].map(num).join(',') + '}').join(',') + '}').join(',\n')}\n};\n\n`;
const fields = [], infos = [], optDecl = [];
for (const [k, s] of Object.entries(S.SCHEMA)) {
  const d = s[0];
  if (typeof d === 'boolean') { fields.push(`  bool ${k} = ${d};`); infos.push(`  {"${k}", PT_BOOL, offsetof(Params, ${k}), nullptr, 0, false}`); }
  else if (typeof d === 'string') {
    const opts = s[1];
    if (!Array.isArray(opts)) throw new Error('string param without options: ' + k);
    optDecl.push(`static const char* const OPT_${k}[] = { ${opts.map((v) => `"${v}"`).join(', ')} };`);
    fields.push(`  int ${k} = ${opts.indexOf(d)}; // ${opts.join(' | ')}`);
    infos.push(`  {"${k}", PT_ENUM, offsetof(Params, ${k}), OPT_${k}, ${opts.length}, true}`);
  } else if (typeof d === 'number') {
    fields.push(`  float ${k} = ${num(d)}; // ${s[1]}..${s[2]} step ${s[3]}`);
    infos.push(`  {"${k}", PT_FLOAT, offsetof(Params, ${k}), nullptr, 0, ${s[3] >= 1}}`);
  } else throw new Error('unknown param type: ' + k);
}
o += `// Every visual parameter. Enums are stored as the index of the option.\nstruct Params {\n${fields.join('\n')}\n};\n\n`;
o += `struct System {\n${Object.entries(S.SYSTEM_DEFAULTS).map(([k, v]) => (typeof v === 'boolean' ? `  bool ${k} = ${v};` : `  float ${k} = ${num(v)};`)).join('\n')}\n};\n\n`;
o += `enum ParamType { PT_FLOAT, PT_ENUM, PT_BOOL };\n// stepped: integer-valued or discrete, so it snaps instead of easing.\nstruct ParamInfo { const char* key; ParamType type; size_t offset; const char* const* options; int nOptions; bool stepped; };\n`;
o += optDecl.join('\n') + '\n';
o += `enum { PARAM_COUNT = ${infos.length} };\nstatic const ParamInfo PARAM_INFO[PARAM_COUNT] = {\n${infos.join(',\n')}\n};\n\n`;
o += `inline const ParamInfo* param_find(const char* key) { for (const ParamInfo& p : PARAM_INFO) if (!strcmp(p.key, key)) return &p; return nullptr; }
// Sets one parameter by its web name. Numbers and booleans come as num; enum values as str.
inline bool params_set(Params& P, const ParamInfo* p, double num, const char* str) {
  char* at = (char*)&P + p->offset;
  if (p->type == PT_BOOL) *(bool*)at = num != 0;
  else if (p->type == PT_FLOAT) *(float*)at = (float)num;
  else { if (!str) return false; for (int i = 0; i < p->nOptions; i++) if (!strcmp(p->options[i], str)) { *(int*)at = i; return true; } return false; }
  return true;
}
inline bool params_set(Params& P, const char* key, double num, const char* str) {
  const ParamInfo* p = param_find(key); return p && params_set(P, p, num, str);
}
// System settings by web name (all numbers; booleans as 0/1).
inline bool system_set(System& S, const char* key, double num) {
${Object.entries(S.SYSTEM_DEFAULTS).map(([k, v]) => `  if (!strcmp(key, "${k}")) { S.${k} = ${typeof v === 'boolean' ? 'num != 0' : '(float)num'}; return true; }`).join('\n')}
  return false;
}
`;
fs.writeFileSync(outPath, o);
